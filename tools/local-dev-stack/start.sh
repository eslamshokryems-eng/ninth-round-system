#!/usr/bin/env bash
# LOCAL ONLY. One command that builds the demo database, starts the stand-in auth/data
# gateway + mail sink + the web app, and prints the URL and demo logins.
#   bash tools/local-dev-stack/start.sh          # start everything (re-seeds the demo DB)
#   bash tools/local-dev-stack/start.sh stop     # stop everything
# Needs: Node 20+, pnpm, PostgreSQL 16 running locally where your user may create databases
# (macOS: brew install postgresql@16 && brew services start postgresql@16; Windows: use WSL).
# Never connects to Supabase or any remote database.
set -eu
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; ROOT="$HERE/../.."
RUN="$HERE/.run"; mkdir -p "$RUN"
stop() { for n in web gateway sink; do [ -f "$RUN/$n.pid" ] && kill "$(cat "$RUN/$n.pid")" 2>/dev/null || true; rm -f "$RUN/$n.pid"; done
         pkill -f "tools/local-dev-stack/gateway.mjs" 2>/dev/null || true; pkill -f "tools/local-dev-stack/mail-sink.mjs" 2>/dev/null || true
         pkill -f "next dev -p 3000" 2>/dev/null || true; }
if [ "${1:-}" = "stop" ]; then stop; echo "stopped"; exit 0; fi
for c in node pnpm psql; do command -v $c >/dev/null || { echo "Missing: $c — install it first (see header of this file)"; exit 1; }; done
pg_isready >/dev/null 2>&1 || { echo "PostgreSQL is not running/reachable. Start it, then re-run."; exit 1; }
stop; sleep 1
[ -d "$ROOT/node_modules" ] || (cd "$ROOT" && pnpm install)
echo "== Building the demo database (synthetic data) =="; bash "$HERE/apply.sh" | tail -3
echo "== Starting mail sink + gateway =="
(cd "$ROOT" && setsid nohup node tools/local-dev-stack/mail-sink.mjs > "$RUN/sink.log" 2>&1 < /dev/null & echo $! > "$RUN/sink.pid") > /dev/null 2>&1
(cd "$ROOT" && setsid nohup node tools/local-dev-stack/gateway.mjs > "$RUN/gateway.log" 2>&1 < /dev/null & echo $! > "$RUN/gateway.pid") > /dev/null 2>&1
for i in $(seq 1 30); do grep -q "SERVICE_ROLE_KEY=" "$RUN/gateway.log" 2>/dev/null && break; sleep 1; done
ENVF="$ROOT/apps/web/.env.local"
if [ ! -f "$ENVF" ]; then
  ANON="$(grep -o 'ANON_KEY=.*' "$RUN/gateway.log" | head -1 | cut -d= -f2-)"; SVC="$(grep -o 'SERVICE_ROLE_KEY=.*' "$RUN/gateway.log" | head -1 | cut -d= -f2-)"
  PEPPER="$(node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))')"
  cat > "$ENVF" <<EOT
# LOCAL DEV ONLY (gitignored). Generated by tools/local-dev-stack/start.sh
NEXT_PUBLIC_SITE_URL=http://localhost:3000
NEXT_PUBLIC_SUPABASE_URL=same-origin
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON
SUPABASE_SERVICE_ROLE_KEY=$SVC
SUPABASE_INTERNAL_URL=http://127.0.0.1:54321
LOCAL_GATEWAY_URL=http://127.0.0.1:54321
DEVICE_VERIFICATION_PEPPER=$PEPPER
RESEND_API_KEY=local-dev-sink
RESEND_FROM_EMAIL=9th Round Local <noreply@9thround.local>
RESEND_API_URL=http://127.0.0.1:54325
EOT
  echo "wrote $ENVF"
fi
echo "== Starting the web app =="
(cd "$ROOT/apps/web" && setsid nohup npx next dev -p 3000 > "$RUN/web.log" 2>&1 < /dev/null & echo $! > "$RUN/web.pid") > /dev/null 2>&1
for i in $(seq 1 90); do curl -s -o /dev/null http://127.0.0.1:3000/login && break; sleep 1; done
cat <<'EOT'

READY  ->  open  http://localhost:3000/login   (on THIS computer)
Password for every demo account: demo1234  (type the email in the "Employee ID" box)
  Super Admin     admin@9thround.local
  Branch Manager  manager@9thround.local
  Coach           coach.one@9thround.local
  Member          member01@9thround.local  (… up to member12)
Staff accounts ask for a 6-digit code. Get it with:  curl -s http://127.0.0.1:54325/last
(members never need a code). Stop everything:  bash tools/local-dev-stack/start.sh stop
EOT
